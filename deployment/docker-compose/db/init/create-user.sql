DECLARE
user_exists NUMBER;
BEGIN
SELECT COUNT(*) INTO user_exists
FROM dba_users
WHERE username = 'STORE';

IF user_exists = 0 THEN
        EXECUTE IMMEDIATE 'CREATE USER STORE IDENTIFIED BY 123';

EXECUTE IMMEDIATE 'GRANT CREATE SESSION TO STORE';
EXECUTE IMMEDIATE 'GRANT CREATE TABLE, CREATE VIEW TO STORE';

EXECUTE IMMEDIATE 'ALTER USER STORE QUOTA UNLIMITED ON USERS';
EXECUTE IMMEDIATE 'ALTER USER STORE DEFAULT ROLE ALL';
EXECUTE IMMEDIATE 'GRANT ALL PRIVILEGES TO STORE';
END IF;
END;
/