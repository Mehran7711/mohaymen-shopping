DECLARE
store_user_exists NUMBER;
    order_user_exists NUMBER;
    keycloak_user_exists NUMBER;
BEGIN

SELECT COUNT(*) INTO store_user_exists
FROM dba_users
WHERE username = 'STORE';

IF store_user_exists = 0 THEN
EXECUTE IMMEDIATE 'CREATE USER STORE IDENTIFIED BY 123';
EXECUTE IMMEDIATE 'GRANT CREATE SESSION TO STORE';
EXECUTE IMMEDIATE 'GRANT CREATE TABLE, CREATE VIEW TO STORE';
EXECUTE IMMEDIATE 'ALTER USER STORE QUOTA UNLIMITED ON USERS';
EXECUTE IMMEDIATE 'ALTER USER STORE DEFAULT ROLE ALL';
EXECUTE IMMEDIATE 'GRANT ALL PRIVILEGES TO STORE';
END IF;

SELECT COUNT(*) INTO order_user_exists
FROM dba_users
WHERE username = 'PAYMENT';

IF order_user_exists = 0 THEN
EXECUTE IMMEDIATE 'CREATE USER PAYMENT IDENTIFIED BY 123';
EXECUTE IMMEDIATE 'GRANT CREATE SESSION TO PAYMENT';
EXECUTE IMMEDIATE 'GRANT CREATE TABLE, CREATE VIEW TO PAYMENT';
EXECUTE IMMEDIATE 'ALTER USER PAYMENT QUOTA UNLIMITED ON USERS';
EXECUTE IMMEDIATE 'ALTER USER PAYMENT DEFAULT ROLE ALL';
EXECUTE IMMEDIATE 'GRANT ALL PRIVILEGES TO PAYMENT';
END IF;


SELECT COUNT(*) INTO keycloak_user_exists
FROM dba_users
WHERE username = 'KEYCLOAK';

IF keycloak_user_exists = 0 THEN
EXECUTE IMMEDIATE 'CREATE USER KEYCLOAK IDENTIFIED BY 123';
EXECUTE IMMEDIATE 'GRANT CREATE SESSION TO KEYCLOAK';
EXECUTE IMMEDIATE 'GRANT CREATE TABLE, CREATE VIEW TO KEYCLOAK';
EXECUTE IMMEDIATE 'ALTER USER KEYCLOAK QUOTA UNLIMITED ON USERS';
EXECUTE IMMEDIATE 'ALTER USER KEYCLOAK DEFAULT ROLE ALL';
EXECUTE IMMEDIATE 'GRANT ALL PRIVILEGES TO KEYCLOAK';
END IF;
END;
